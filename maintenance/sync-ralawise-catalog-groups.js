const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { parse } = require('csv-parse');
const { pool } = require('../config/database');
const { CATALOG_GROUPS, classifyCatalogGroups } = require('../services/catalogGroupClassifier');

const apply = process.argv.includes('--apply');
const fileArgument = process.argv.find(argument => argument.startsWith('--file='));
const manifestPath = path.join(__dirname, 'ralawise-catalog-groups.json');
const sourcePath = path.resolve(fileArgument ? fileArgument.slice('--file='.length) : manifestPath);
const sourceHash = crypto.createHash('sha256').update(fs.readFileSync(sourcePath)).digest('hex');

async function readAssignments() {
  const assignments = new Map();
  let rowCount = 0;

  if (!fileArgument) {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    for (const assignment of manifest.assignments || []) {
      assignments.set(String(assignment.styleCode).toUpperCase(), new Set(assignment.groups || []));
    }
    return { assignments, rowCount: manifest.sourceRows || 0 };
  }

  await new Promise((resolve, reject) => {
    fs.createReadStream(sourcePath)
      .pipe(parse({ columns: true, bom: true, relax_quotes: true, relax_column_count: true }))
      .on('data', row => {
        rowCount += 1;
        const styleCode = String(row['Style Code'] || '').trim().toUpperCase();
        if (!styleCode) return;

        const groups = classifyCatalogGroups(row);
        if (!groups.length) return;
        if (!assignments.has(styleCode)) assignments.set(styleCode, new Set());
        for (const group of groups) assignments.get(styleCode).add(`${group.type}:${group.slug}`);
      })
      .on('end', resolve)
      .on('error', reject);
  });

  return { assignments, rowCount };
}

async function createSchema(client) {
  await client.query(`
    CREATE TABLE IF NOT EXISTS catalog_groups (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      group_type varchar(20) NOT NULL CHECK (group_type IN ('sector', 'collection')),
      name varchar(200) NOT NULL,
      slug varchar(200) NOT NULL,
      display_order integer DEFAULT 0,
      created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (group_type, slug)
    );
    CREATE TABLE IF NOT EXISTS product_catalog_groups (
      product_id integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
      catalog_group_id integer NOT NULL REFERENCES catalog_groups(id) ON DELETE CASCADE,
      source varchar(50) NOT NULL DEFAULT 'ralawise-categorisation',
      created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (product_id, catalog_group_id)
    );
    CREATE INDEX IF NOT EXISTS idx_product_catalog_groups_group
      ON product_catalog_groups (catalog_group_id, product_id);
    CREATE TABLE IF NOT EXISTS catalog_group_import_state (
      id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
      source_hash varchar(64) NOT NULL,
      applied_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
    );
  `);
}

async function insertGroups(client) {
  for (const group of CATALOG_GROUPS) {
    await client.query(`
      INSERT INTO catalog_groups (group_type, name, slug, display_order)
      VALUES ($1, $2, $3, $4)
      ON CONFLICT (group_type, slug) DO UPDATE SET
        name = EXCLUDED.name,
        display_order = EXCLUDED.display_order,
        updated_at = CURRENT_TIMESTAMP
    `, [group.type, group.name, group.slug, group.displayOrder]);
  }
}

async function stageAssignments(client, assignments) {
  await client.query(`
    CREATE TEMP TABLE staged_catalog_assignments (
      style_code varchar(50) NOT NULL,
      group_type varchar(20) NOT NULL,
      group_slug varchar(200) NOT NULL,
      PRIMARY KEY (style_code, group_type, group_slug)
    ) ON COMMIT DROP
  `);

  const rows = [];
  for (const [styleCode, groupKeys] of assignments) {
    for (const groupKey of groupKeys) {
      const separator = groupKey.indexOf(':');
      rows.push([styleCode, groupKey.slice(0, separator), groupKey.slice(separator + 1)]);
    }
  }

  const batchSize = 1000;
  for (let start = 0; start < rows.length; start += batchSize) {
    const batch = rows.slice(start, start + batchSize);
    const values = [];
    const placeholders = batch.map((row, index) => {
      const offset = index * 3;
      values.push(...row);
      return `($${offset + 1}, $${offset + 2}, $${offset + 3})`;
    });
    await client.query(`
      INSERT INTO staged_catalog_assignments (style_code, group_type, group_slug)
      VALUES ${placeholders.join(',')}
      ON CONFLICT DO NOTHING
    `, values);
  }
}

async function report(client, rowCount, assignments) {
  const summary = await client.query(`
    SELECT
      cg.group_type,
      cg.name,
      cg.slug,
      COUNT(DISTINCT p.style_code)::integer AS styles,
      COUNT(DISTINCT p.id)::integer AS skus
    FROM catalog_groups cg
    LEFT JOIN staged_catalog_assignments sca
      ON sca.group_type = cg.group_type AND sca.group_slug = cg.slug
    LEFT JOIN products p ON UPPER(p.style_code) = sca.style_code
      AND EXISTS (
        SELECT 1 FROM styles s
        JOIN suppliers sup ON sup.id = s.supplier_id
        WHERE s.style_code = p.style_code AND sup.slug = 'ralawise'
      )
    GROUP BY cg.id
    ORDER BY cg.group_type DESC, cg.display_order
  `);
  const matchStats = await client.query(`
    SELECT
      COUNT(DISTINCT sca.style_code)::integer AS labelled_source_styles,
      COUNT(DISTINCT p.style_code)::integer AS matched_database_styles,
      COUNT(DISTINCT sca.style_code) FILTER (WHERE p.id IS NULL)::integer AS unmatched_source_styles
    FROM staged_catalog_assignments sca
    LEFT JOIN products p ON UPPER(p.style_code) = sca.style_code
      AND EXISTS (
        SELECT 1 FROM styles s
        JOIN suppliers sup ON sup.id = s.supplier_id
        WHERE s.style_code = p.style_code AND sup.slug = 'ralawise'
      )
  `);

  console.log(JSON.stringify({
    mode: apply ? 'apply' : 'dry-run',
    sourcePath,
    sourceHash,
    sourceRows: rowCount,
    sourceStylesWithGroups: assignments.size,
    ...matchStats.rows[0],
    groups: summary.rows
  }, null, 2));
}

async function applyAssignments(client) {
  await client.query(`
    DELETE FROM product_catalog_groups pcg
    USING catalog_groups cg
    WHERE pcg.catalog_group_id = cg.id
      AND cg.group_type IN ('sector', 'collection')
      AND pcg.source = 'ralawise-categorisation'
  `);
  const result = await client.query(`
    INSERT INTO product_catalog_groups (product_id, catalog_group_id, source)
    SELECT DISTINCT p.id, cg.id, 'ralawise-categorisation'
    FROM staged_catalog_assignments sca
    JOIN products p ON UPPER(p.style_code) = sca.style_code
    JOIN styles s ON s.style_code = p.style_code
    JOIN suppliers sup ON sup.id = s.supplier_id AND sup.slug = 'ralawise'
    JOIN catalog_groups cg
      ON cg.group_type = sca.group_type AND cg.slug = sca.group_slug
    ON CONFLICT DO NOTHING
  `);
  await client.query(`
    INSERT INTO catalog_group_import_state (id, source_hash, applied_at)
    VALUES (1, $1, CURRENT_TIMESTAMP)
    ON CONFLICT (id) DO UPDATE SET source_hash = EXCLUDED.source_hash, applied_at = EXCLUDED.applied_at
  `, [sourceHash]);
  console.log(`Applied ${result.rowCount} product/group relationships.`);
}

async function main() {
  if (!fs.existsSync(sourcePath)) throw new Error(`Source file not found: ${sourcePath}`);
  const { assignments, rowCount } = await readAssignments();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await createSchema(client);
    await insertGroups(client);
    if (apply) {
      const previous = await client.query('SELECT source_hash FROM catalog_group_import_state WHERE id = 1');
      if (previous.rows[0]?.source_hash === sourceHash) {
        await client.query('ROLLBACK');
        console.log('Catalog groups are already current; no database changes were needed.');
        return;
      }
    }
    await stageAssignments(client, assignments);
    await report(client, rowCount, assignments);
    if (apply) {
      await applyAssignments(client);
      await client.query('COMMIT');
    } else {
      await client.query('ROLLBACK');
      console.log('Dry run complete. No database changes were saved.');
    }
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
